import { createRoot } from 'react-dom/client';
import {lazy,Suspense} from 'react';
import Home from '../app/page';
const Join=lazy(()=>import('../app/join/page'));
const Presenter=lazy(()=>import('./presenter-account'));
const Project=lazy(()=>import('../app/project/page'));
const Help=lazy(()=>import('./help'));
const About=lazy(()=>import('../app/about/page'));
import UpdateCheck from './update-check';
import '../app/globals.css';
import '../app/design-system.css';
import '../app/team-experience.css';
import '../app/voice-input.css';
import '../app/comment-thread.css';
import '../app/discussion-map.css';

const base = window.__WORKSHOP_BASE_PATH__ || '/workshops';
const route = location.pathname.slice(base.length).replace(/\/$/, '') || '/';
const Page = route === '/join' ? Join : route === '/presenter' ? Presenter : route === '/project' ? Project : route === '/about' ? About : Home;
const loading=<main className="center-page" role="status"><span className="spinner"/>Loading workshop… / جارٍ تحميل الورشة…</main>;
createRoot(document.getElementById('root')!).render(<><Suspense fallback={loading}><Page /></Suspense>{route!=='/project'&&<Suspense fallback={null}><Help/></Suspense>}<UpdateCheck presenter={route==='/presenter'}/></>);
